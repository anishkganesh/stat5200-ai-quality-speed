# Descriptive statistics and proposal macros only; no treatment effects are estimated.
# Run from the repository root: Rscript code/descriptives.R
args <- commandArgs(trailingOnly = TRUE)
input <- if (length(args) >= 1L) args[1L] else 'data/derived/participants.csv'
outdir <- if (length(args) >= 2L) args[2L] else 'results/tables'
dir.create(outdir, showWarnings = FALSE, recursive = TRUE)
x <- read.csv(input, stringsAsFactors = FALSE)
stopifnot(nrow(x) == 453L)
main <- x[x$incentive_arm != 'exact', ]
stopifnot(nrow(main) == 359L)
variables <- c('time1', 'time2', 'overall1', 'overall2')
rows <- list()
k <- 0L
for (sample_name in c('all_clean', 'main_linear_convex')) {
  d <- if (sample_name == 'all_clean') x else main
  for (group_name in c('all', 'control', 'treatment')) {
    dd <- switch(group_name, all = d,
                 control = d[d$treatment == 0, ],
                 treatment = d[d$treatment == 1, ])
    for (variable in variables) {
      values <- dd[[variable]]
      z <- values[!is.na(values)]
      k <- k + 1L
      rows[[k]] <- data.frame(
        sample = sample_name, group = group_name, variable = variable,
        group_n = nrow(dd), nonmissing_n = length(z), missing_n = sum(is.na(values)),
        mean = mean(z), sd = sd(z), min = min(z),
        p25 = unname(quantile(z, 0.25)), median = median(z),
        p75 = unname(quantile(z, 0.75)), max = max(z))
    }
  }
}
results <- do.call(rbind, rows)
write.csv(results, file.path(outdir, 'descriptive_statistics.csv'),
          row.names = FALSE, na = '')

# These counts describe availability, not a new outcome or analysis sample filter.
complete_post <- complete.cases(main[, c('time2', 'overall2')])
complete_all <- complete.cases(main[, variables])
stopifnot(sum(complete_post) == 352L, sum(complete_all) == 341L)
macro_names <- c('HWTotalN', 'HWMainN', 'HWControlN', 'HWTreatedN',
                 'HWPostCompleteN', 'HWAllCompleteN',
                 'HWPreTimeN', 'HWPostTimeN', 'HWPreGradeN', 'HWPostGradeN',
                 'HWMeanPreTime', 'HWMeanPostTime', 'HWMeanPreGrade', 'HWMeanPostGrade')
macro_values <- c(nrow(x), nrow(main), sum(main$treatment == 0), sum(main$treatment == 1),
                  sum(complete_post), sum(complete_all),
                  sum(!is.na(main$time1)), sum(!is.na(main$time2)),
                  sum(!is.na(main$overall1)), sum(!is.na(main$overall2)),
                  sprintf('%.2f', mean(main$time1, na.rm = TRUE)),
                  sprintf('%.2f', mean(main$time2, na.rm = TRUE)),
                  sprintf('%.2f', mean(main$overall1, na.rm = TRUE)),
                  sprintf('%.2f', mean(main$overall2, na.rm = TRUE)))
commands <- sprintf('\\newcommand{\\%s}{%s}', macro_names, macro_values)
writeLines(c('% Generated by code/descriptives.R; do not edit numeric values manually.',
             commands), file.path(outdir, 'proposal_stats.tex'))
capture.output(sessionInfo(), file = file.path(outdir, 'R_session_info.txt'))
print(results[results$sample == 'main_linear_convex',
              c('group','variable','nonmissing_n','mean','sd')], row.names = FALSE)
